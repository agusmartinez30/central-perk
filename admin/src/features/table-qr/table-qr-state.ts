/** Views of the single `/tables/qr` route. */
export type TableQrView = "list" | "editor" | "detail" | "material";

export type TableEditorState = {
  /** null while creating a table. */
  id: string | null;
  draft: TableDraft;
  /** Errors show only after a blocked save. */
  submitted: boolean;
};

export type BulkPrintState = { space: SpaceFilter; size: PrintSizeId; selection: string[] };

/** Inline 09A space form (create or rename); errors show after a blocked save. */
export type SpaceEditorState = { id: SpaceId | null; name: string; submitted: boolean };

export type TableQrState = {
  /** 09A "Espacios" as edited in this session. */
  spaces: readonly VenueSpace[];
  tables: readonly VenueTable[];
  sessions: Record<number, SessionStatus>;
  /** ISO date of the service day ("Generado hoy"). */
  today: string;
  /** Session user, who generates and rotates credentials. */
  staffName: string;
  view: TableQrView;
  query: string;
  /** 09A "Espacio" filter. */
  space: SpaceFilter;
  configuration: ConfigurationFilter;
  editor: TableEditorState | null;
  /** Table of the 09C QR detail or the 09D printable material. */
  detailId: string | null;
  /** 09F "¿Regenerar código QR?" is open over 09C. */
  regenerating: boolean;
  /** 09E "Imprimir códigos QR" modal over the list. */
  bulk: BulkPrintState | null;
  /** Last action outcome, announced to screen readers. */
  spaceEditor: SpaceEditorState | null;
  notice: string | null;
};

export type TableQrAction =
  | { type: "set-query"; query: string }
  | { type: "set-space"; space: SpaceFilter }
  | { type: "set-configuration"; configuration: ConfigurationFilter }
  | { type: "toggle-enabled"; id: string }
  | { type: "open-edit"; id: string }
  | { type: "open-new" }
  | { type: "editor-set-field"; field: "label" | "capacity" | "description"; value: string }
  | { type: "editor-set-field"; field: "spaceId"; value: TableDraft["spaceId"] }
  | { type: "editor-set-field"; field: "enabled"; value: boolean }
  /** `token` is the credential a new table receives (generated by the screen, unique). */
  | { type: "editor-save"; token: string }
  | { type: "close-editor" }
  | { type: "open-detail"; id: string }
  | { type: "open-material"; id: string }
  | { type: "close-detail" }
  /** From the list menu (`id`) or the open 09C drawer. */
  | { type: "open-regenerate"; id?: string }
  | { type: "cancel-regenerate" }
  /** `token` is the new credential (generated by the screen, unique). */
  | { type: "confirm-regenerate"; token: string }
  | { type: "open-bulk" }
  | { type: "close-bulk" }
  | { type: "bulk-set-space"; space: SpaceFilter }
  /** Without `id`: "Crear espacio". */
  | { type: "open-space-editor"; id?: SpaceId }
  | { type: "space-set-name"; name: string }
  | { type: "space-save" }
  | { type: "space-cancel" }
  | { type: "bulk-set-size"; size: PrintSizeId }
  | { type: "bulk-toggle"; id: string }
  | { type: "bulk-toggle-all" };

/** Session copy of the canonical tables; live session status comes from the service day. */
export function createTableQrState(): TableQrState {
  return {
    spaces: SERVICE_DAY.spaces,
    tables: SERVICE_DAY.tables,
    sessions: getSessionStatuses(SERVICE_DAY),
    today: SERVICE_DAY.date,
    staffName: DEMO_STAFF.name,
    view: "list",
    query: "",
    space: "all",
    configuration: "all",
    editor: null,
    detailId: null,
    spaceEditor: null,
    regenerating: false,
    bulk: null,
    notice: null,
  };
}

const sessionOf = (state: TableQrState, table: VenueTable): SessionStatus => state.sessions[table.number] ?? "available";

function saveEditor(state: TableQrState, token: string): TableQrState {
  const { editor } = state;
  if (!editor) return state;
  const errors = validateTableDraft(editor.draft, state.tables, editor.id, state.spaces);
  if (Object.keys(errors).length > 0) {
    return { ...state, editor: { ...editor, submitted: true }, notice: "Revisá los datos marcados." };
  }
  const saved = editor.id ? state.tables.find((table) => table.id === editor.id) ?? null : null;
  if (saved && getTableChanges(saved, editor.draft).length === 0) {
    return { ...state, view: "list", editor: null, notice: `Sin cambios en ${saved.label}.` };
  }
  const result = applyTableDraft(state.tables, editor.id, editor.draft, {
    today: state.today,
    staffName: state.staffName,
    createToken: () => token,
  });
  const label = result.tables.find((table) => table.id === result.id)?.label ?? "";
  return {
    ...state,
    tables: result.tables,
    view: "list",
    editor: null,
    notice: editor.id ? `${label} guardada.` : `${label} creada.`,
  };
}

export function tableQrReducer(state: TableQrState, action: TableQrAction): TableQrState {
  switch (action.type) {
    case "set-query":
      return { ...state, query: action.query };
    case "set-space":
      return { ...state, space: action.space };
    case "set-configuration":
      return { ...state, configuration: action.configuration };
    case "toggle-enabled": {
      const table = state.tables.find((candidate) => candidate.id === action.id);
      if (!table) return state;
      const toggle = getQuickToggle(table, sessionOf(state, table));
      if (!toggle.allowed) return { ...state, notice: toggle.reason ?? null };
      return {
        ...state,
        tables: setTableEnabled(state.tables, table.id, !table.enabled),
        notice: `${table.label} ${table.enabled ? "deshabilitada" : "habilitada"}.`,
      };
    }
    case "open-edit": {
      const table = state.tables.find((candidate) => candidate.id === action.id);
      if (!table) return state;
      return { ...state, view: "editor", editor: { id: table.id, draft: toTableDraft(table), submitted: false }, notice: null };
    }
    case "open-new":
      return {
        ...state,
        view: "editor",
        editor: { id: null, draft: createEmptyTableDraft(state.tables, state.spaces), submitted: false },
        notice: null,
      };
    case "editor-set-field":
      if (!state.editor) return state;
      return { ...state, editor: { ...state.editor, draft: { ...state.editor.draft, [action.field]: action.value } } };
    case "editor-save":
      return saveEditor(state, action.token);
    case "close-editor":
      return { ...state, view: "list", editor: null };
    case "open-detail":
    case "open-material":
      if (!state.tables.some((table) => table.id === action.id)) return state;
      return {
        ...state,
        view: action.type === "open-detail" ? "detail" : "material",
        detailId: action.id,
        regenerating: false,
        notice: null,
      };
    case "close-detail":
      return { ...state, view: "list", detailId: null, regenerating: false };
    case "open-regenerate": {
      const id = action.id ?? state.detailId;
      if (!id || !state.tables.some((table) => table.id === id)) return state;
      return { ...state, view: "detail", detailId: id, regenerating: true, notice: null };
    }
    case "cancel-regenerate":
      return { ...state, regenerating: false };
    case "confirm-regenerate": {
      const table = state.tables.find((candidate) => candidate.id === state.detailId);
      if (!table) return state;
      return {
        ...state,
        tables: regenerateTableQr(state.tables, table.id, {
          today: state.today,
          staffName: state.staffName,
          createToken: () => action.token,
        }),
        regenerating: false,
        notice: table.qr
          ? `Código QR de ${table.label} regenerado. El código anterior dejó de funcionar.`
          : `Código QR de ${table.label} generado.`,
      };
    }
    case "open-bulk":
      return {
        ...state,
        view: "list",
        bulk: { space: "all", size: "a6", selection: selectSpace(getPrintableTables(state.tables), "all") },
        notice: null,
      };
    case "close-bulk":
      return { ...state, bulk: null };
    case "bulk-set-space":
      if (!state.bulk) return state;
      return {
        ...state,
        bulk: { ...state.bulk, space: action.space, selection: selectSpace(getPrintableTables(state.tables), action.space) },
      };
    case "bulk-set-size":
      return state.bulk ? { ...state, bulk: { ...state.bulk, size: action.size } } : state;
    case "bulk-toggle":
      return state.bulk ? { ...state, bulk: { ...state.bulk, selection: toggleSelection(state.bulk.selection, action.id) } } : state;
    case "open-space-editor": {
      const space = action.id ? state.spaces.find((candidate) => candidate.id === action.id) : undefined;
      if (action.id && !space) return state;
      return { ...state, spaceEditor: { id: space?.id ?? null, name: space?.name ?? "", submitted: false }, notice: null };
    }
    case "space-set-name":
      return state.spaceEditor ? { ...state, spaceEditor: { ...state.spaceEditor, name: action.name } } : state;
    case "space-save": {
      const editor = state.spaceEditor;
      if (!editor) return state;
      const error = validateSpaceName(editor.name, state.spaces, editor.id);
      if (error) return { ...state, spaceEditor: { ...editor, submitted: true }, notice: error };
      const result = saveSpace(state.spaces, editor.id, editor.name);
      return {
        ...state,
        spaces: result.spaces,
        spaceEditor: null,
        notice: `Espacio ${editor.name.trim()} ${editor.id ? "guardado" : "creado"}.`,
      };
    }
    case "space-cancel":
      return { ...state, spaceEditor: null };
    case "bulk-toggle-all": {
      if (!state.bulk) return state;
      const visible = filterBySpace(getPrintableTables(state.tables), state.bulk.space);
      return { ...state, bulk: { ...state.bulk, selection: toggleAll(visible, state.bulk.selection) } };
    }
  }
}

/** A row plus its "Más" quick enable/disable action. */
export type ListRow = TableRow & { toggle: QuickToggle };

export type ListView = { metrics: TableMetrics; spaces: SpaceCard[]; rows: ListRow[]; total: number };

export function getListView(state: TableQrState): ListView {
  const rows = getTableRows(state.tables, state.sessions, state.spaces);
  return {
    metrics: getTableMetrics(state.tables),
    spaces: getSpaceCards(state.spaces, state.tables),
    rows: filterTableRows(rows, { query: state.query, spaceId: state.space, configuration: state.configuration }).map(
      (row) => {
        const table = state.tables.find((candidate) => candidate.id === row.id)!;
        return { ...row, toggle: getQuickToggle(table, sessionOf(state, table)) };
      },
    ),
    total: rows.length,
  };
}

export type EditorView = {
  title: string;
  /** "ID estable · tbl_07 · versión 18". */
  idLabel: string;
  /** 09B "Sesión activa" warning: the table has an open session. */
  activeSession: boolean;
  errors: TableDraftErrors;
};

export function getEditorView(state: TableQrState): EditorView | null {
  const { editor } = state;
  if (!editor) return null;
  const table = editor.id ? state.tables.find((candidate) => candidate.id === editor.id) : undefined;
  const errors = editor.submitted ? validateTableDraft(editor.draft, state.tables, editor.id, state.spaces) : {};
  if (!table) {
    const id = `tbl_${String(nextTableNumber(state.tables)).padStart(2, "0")}`;
    return { title: "Nueva mesa", idLabel: `ID estable · ${id} · se asigna al guardar`, activeSession: false, errors };
  }
  return {
    title: "Editar mesa",
    idLabel: `ID estable · ${table.id} · versión ${table.version}`,
    activeSession: sessionOf(state, table) !== "available",
    errors,
  };
}

export type DetailView = {
  tableId: string;
  label: string;
  /** "Código QR · Mesa 07". */
  title: string;
  /** "Salón · 4 personas". */
  meta: string;
  /** "Mesa 07 · Salón". */
  identity: string;
  /** "ID interno estable · tbl_07". */
  stableId: string;
  /** QR target; null when the table has no credential. */
  url: string | null;
  displayUrl: string | null;
  /** Disabled tables keep their token, but the code does not admit new sessions. */
  enabled: boolean;
  history: CredentialHistoryRow[];
};

const findDetail = (state: TableQrState) => state.tables.find((table) => table.id === state.detailId);

export function getDetailView(state: TableQrState): DetailView | null {
  const table = findDetail(state);
  if (!table) return null;
  const spaceName = getSpaceName(state.spaces, table.spaceId);
  const url = table.qr ? buildTableQrUrl({ number: table.number, token: table.qr.token }) : null;
  return {
    tableId: table.id,
    label: table.label,
    title: `Código QR · ${table.label}`,
    meta: `${spaceName} · ${formatCapacity(table.capacity)}`,
    identity: `${table.label} · ${spaceName}`,
    stableId: `ID interno estable · ${table.id}`,
    url,
    displayUrl: url ? formatDisplayUrl(url) : null,
    enabled: table.enabled,
    history: getCredentialHistory(table, state.today),
  };
}

export type PrintCard = { tableId: string; label: string; title: string; url: string };

function toPrintCard(table: VenueTable): PrintCard {
  return {
    tableId: table.id,
    label: table.label,
    title: formatCardTitle(table.label),
    url: buildTableQrUrl({ number: table.number, token: table.qr?.token ?? "" }),
  };
}

export type MaterialView = {
  /** The table's card; null when it cannot be printed (disabled or without QR). */
  card: PrintCard | null;
  /** 09D "Hoja A4 · 6 tarjetas": the first compact sheet of the printable tables. */
  sheet: PrintCard[];
};

export function getMaterialView(state: TableQrState): MaterialView | null {
  const table = findDetail(state);
  if (!table) return null;
  const printable = getPrintableTables(state.tables);
  const [firstSheet = []] = paginate(printable, getPrintSize("compact").perSheet);
  return {
    card: printable.includes(table) ? toPrintCard(table) : null,
    sheet: firstSheet.map(toPrintCard),
  };
}

export type BulkRow = { id: string; label: string; selected: boolean };

export type BulkView = {
  /** "12 seleccionados". */
  countLabel: string;
  rows: BulkRow[];
  /** Every visible table is selected ("✓ Seleccionar todos" clears them). */
  allSelected: boolean;
  spaces: readonly VenueSpace[];
  space: SpaceFilter;
  size: PrintSizeId;
  sizes: readonly PrintSize[];
  perSheet: number;
  /** Selected cards split into A4 sheets. */
  sheets: PrintCard[][];
  /** "VISTA PREVIA · A4": the first sheet. */
  preview: PrintCard[];
  canExport: boolean;
};

export function getBulkView(state: TableQrState): BulkView | null {
  const { bulk } = state;
  if (!bulk) return null;
  const printable = getPrintableTables(state.tables);
  const visible = filterBySpace(printable, bulk.space);
  const selected = getSelectedTables(printable, bulk.selection);
  const { perSheet } = getPrintSize(bulk.size);
  const sheets = paginate(selected.map(toPrintCard), perSheet);
  return {
    countLabel: `${selected.length} ${selected.length === 1 ? "seleccionado" : "seleccionados"}`,
    rows: visible.map((table) => ({
      id: table.id,
      label: `${table.label} · ${getSpaceName(state.spaces, table.spaceId)}`,
      selected: bulk.selection.includes(table.id),
    })),
    allSelected: visible.length > 0 && visible.every((table) => bulk.selection.includes(table.id)),
    spaces: state.spaces,
    space: bulk.space,
    size: bulk.size,
    sizes: PRINT_SIZES,
    perSheet,
    sheets,
    preview: sheets[0] ?? [],
    canExport: selected.length > 0,
  };
}

export type SpaceEditorView = { id: SpaceId | null; name: string; error: string | null };

/** The inline 09A space form; the error shows only after a blocked save. */
export function getSpaceEditorView(state: TableQrState): SpaceEditorView | null {
  const editor = state.spaceEditor;
  if (!editor) return null;
  return {
    id: editor.id,
    name: editor.name,
    error: editor.submitted ? validateSpaceName(editor.name, state.spaces, editor.id) : null,
  };
}
